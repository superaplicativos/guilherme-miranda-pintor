// ============================================================
// GERENCIADOR DE IDIOMA (com auto-detecção de navegador aprimorada)
// ============================================================
const i18nManager = {
  current: 'pt',
  available: ['pt', 'en', 'es', 'fr', 'de', 'zh', 'hi'],

  init() {
    // 1. Verificar URL (?lang=xx) — shareable links
    const urlParams = new URLSearchParams(window.location.search);
    const urlLang = urlParams.get('lang');
    if (urlLang && this.available.includes(urlLang)) {
      this.current = urlLang;
    } else {
      // 2. Verificar preferência salva
      const saved = localStorage.getItem('cosmos-lang');
      if (saved && this.available.includes(saved)) {
        this.current = saved;
      } else {
        // 3. Auto-detecção do navegador (mapeamento robusto)
        this.current = this.detectBrowserLang();
      }
    }
    this.apply();
    this.updateToggle();
  },

  detectBrowserLang() {
    const browserLangs = navigator.languages || [navigator.language || navigator.userLanguage || 'pt'];
    for (const bl of browserLangs) {
      const lower = bl.toLowerCase();
      if (lower.startsWith('pt')) return 'pt';
      if (lower.startsWith('en')) return 'en';
      if (lower.startsWith('es')) return 'es';
      if (lower.startsWith('fr')) return 'fr';
      if (lower.startsWith('de')) return 'de';
      if (lower.startsWith('zh')) return 'zh';
      if (lower.startsWith('hi')) return 'hi';
    }
    return 'pt'; // fallback
  },

  setLanguage(lang) {
    if (!this.available.includes(lang)) return;
    this.current = lang;
    localStorage.setItem('cosmos-lang', lang);
    this.apply();
    this.updateToggle();
    this.updateDynamicContent();
    // Atualizar URL sem reload pra shareable
    const url = new URL(window.location);
    url.searchParams.set('lang', lang);
    window.history.replaceState({}, '', url);
  },

  toggle() {
    // Ciclo: pt → en → es → fr → de → zh → hi → pt
    const idx = this.available.indexOf(this.current);
    const next = this.available[(idx + 1) % this.available.length];
    this.setLanguage(next);
  },

  t(key) {
    return (I18N[this.current] && I18N[this.current][key]) || I18N.pt[key] || key;
  },

  apply() {
    const meta = I18N[this.current] ? I18N[this.current]._meta : I18N.pt._meta;
    document.documentElement.lang = meta.html_lang;

    // Atualizar title e meta tags dinamicamente (SEO crítico)
    document.title = meta.title;
    this.setMetaTag('description', meta.description);
    this.setMetaTag('keywords', meta.keywords);

    // Atualizar Open Graph
    this.setMetaProperty('og:title', meta.title);
    this.setMetaProperty('og:description', meta.description);
    this.setMetaProperty('og:locale', meta.lang_code);

    // Atualizar elementos com data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation) el.textContent = translation;
    });

    // Atualizar placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation) el.placeholder = translation;
    });

    // Atualizar role e tagline dinâmicos do BIO
    // hero.role e hero.tagline agora usam data-i18n (suporte a 7 idiomas)
  },

  setMetaTag(name, content) {
    let el = document.querySelector(`meta[name="${name}"]`);
    if (!el) {
      el = document.createElement('meta');
      el.setAttribute('name', name);
      document.head.appendChild(el);
    }
    el.setAttribute('content', content);
  },

  setMetaProperty(property, content) {
    let el = document.querySelector(`meta[property="${property}"]`);
    if (!el) {
      el = document.createElement('meta');
      el.setAttribute('property', property);
      document.head.appendChild(el);
    }
    el.setAttribute('content', content);
  },

  updateToggle() {
    const btn = document.getElementById('lang-toggle');
    if (!btn) return;
    const meta = I18N[this.current]._meta;
    // Atualizar spans existentes (flag, code)
    const flagSpan = btn.querySelector('.lang-flag');
    const codeSpan = btn.querySelector('.lang-code');
    if (flagSpan) flagSpan.textContent = meta.flag;
    if (codeSpan) codeSpan.textContent = this.current.toUpperCase();
    btn.setAttribute('aria-label', `Selecionar idioma (atual: ${meta.lang_name})`);

    // Marcar item ativo no menu dropdown
    document.querySelectorAll('#lang-menu li').forEach(li => {
      li.classList.toggle('is-active', li.dataset.lang === this.current);
    });
  },

  updateDynamicContent() {
    if (window.renderPortfolio) window.renderPortfolio();
    if (window.renderCatalogue) window.renderCatalogue();
    if (window.renderShop) window.renderShop();
    if (window.renderExhibitions) window.renderExhibitions();
    if (window.renderBio) window.renderBio();
    if (window.renderHeroStats) window.renderHeroStats();
    if (window.renderBeco) window.renderBeco();
    if (window.renderBooks) window.renderBooks();
    if (window.ScrollTrigger) setTimeout(() => ScrollTrigger.refresh(), 100);
  },

  get lang() { return this.current; },
  get langName() { return I18N[this.current]._meta.lang_name; },
  get langCode() { return I18N[this.current]._meta.lang_code; }
};

if (typeof window !== 'undefined') {
  window.i18n = i18nManager;
  window.t = (key) => i18nManager.t(key);
  window.I18N_LANGS = ['pt', 'en', 'es', 'fr', 'de', 'zh', 'hi'];
}
